/**
 * Entry point of the Elsa chatbot.
 */
public class Elsa {
    public static void main(String[] args) {
        // Each "\\" in the source produces a single backslash in the ASCII-art banner.
        String banner = " _____ _           \n"
                + "|  ___| |___  __ _ \n"
                + "| |__ | / __|/ _` |\n"
                + "|  __|| \\__ \\ (_| |\n"
                + "|_____|_|___/\\__,_|\n";
        System.out.println(banner);
    }
}
